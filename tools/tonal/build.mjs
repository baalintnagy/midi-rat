import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { transformSync } from "@babel/core";
import presetEnv from "@babel/preset-env";

const source = await readFile(new URL("./upstream/tonal-5.1.3.min.js", import.meta.url));
const digest = createHash("sha256").update(source).digest("hex");
if (digest !== "20454ef1ea3cf6076e12e11dc7ad369dc840c1b840c66d8d8f4367429300633d") {
  throw new Error("The pinned upstream Tonal bundle has changed");
}
const result = transformSync(source.toString("utf8"), {
  presets: [[presetEnv, { targets: { ie: "11" }, modules: false }]],
  sourceType: "script",
  comments: true,
  compact: true,
  babelrc: false,
  configFile: false
});
await writeFile(
  new URL("../../src/main/resources/vendor/tonal/tonal-5.1.3.es5.js", import.meta.url),
  "/* Tonal 5.1.3, MIT (c) 2015 danigb. See LICENSE. Generated by tools/tonal. */\n" +
    result.code + "\n"
);
